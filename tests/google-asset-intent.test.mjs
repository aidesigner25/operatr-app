import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import vm from "node:vm";
import ts from "typescript";
const code = ts.transpileModule(readFileSync(new URL("../src/lib/shared/google-asset-intent.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} }; vm.runInNewContext(code, context);
test("requires an explicit single file creation request", () => {
  const intent = context.exports.requestedGoogleAsset;
  assert.equal(intent("Research Apple and create a Google Doc with your findings"), "doc");
  assert.equal(intent("Please make a Google Sheet for this report"), "sheet");
  assert.equal(intent("Excellent, could you please make me a doc conducting the same report, with the same linkedin scan, outlook, and key investment factors, but for costco?"), "doc");
  assert.equal(intent("Please create a spreadsheet of the results"), "sheet");
  assert.equal(intent("Create a Google spreadsheet for the report"), "sheet");
  assert.equal(intent("Make a Google document for the report"), "doc");
  assert.equal(intent("Can you give me one more brief sheet comparing public opinions on Apple and Samsung?"), "sheet");
  assert.equal(intent("Another quick sheet comparing Apple and Samsung, please"), "sheet");
  assert.equal(intent("Please turn this into a short Google Sheet"), "sheet");
  assert.equal(intent("Can you make a new concise spreadsheet?"), "sheet");
  assert.equal(intent("I have another sheet already"), null);
  assert.equal(intent("Please give me a summary of the previous sheet"), null);
  assert.equal(intent("Could you make a report about the sheet?"), null);
  assert.equal(intent("Make a report as a Google Sheet"), "sheet");
  assert.equal(intent("I don't need another sheet"), null);
  assert.equal(intent("Please answer without another brief sheet"), null);
  assert.equal(intent("What did the previous sheet compare?"), null);
  assert.equal(intent("Don't provide another brief sheet"), null);
  assert.equal(intent("Make me a Word document"), null);
  assert.equal(intent("How do I create a Google Doc?"), null);
  assert.equal(intent("Don't create a Google Doc"), null);
  assert.equal(intent("Create a Google Doc and Google Sheet"), null);
});
